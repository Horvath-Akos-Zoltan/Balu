int main(int argc, char* argv[]) {
    _setmode(0, _O_U16TEXT);
    _setmode(1, _O_U16TEXT);

    int count = 0;
    const vector<wstring> args = GetCommandLineArgs(count);
    CompilerOptions.User.Args = ParseCommandLineArgs(args);

    vector<wstring> *freeArgs = &CompilerOptions.User.Args.freeArgs;
    vector<wstring> *flags = &CompilerOptions.User.Args.flags;
    vector<CommandLineValuePair> *keyValuePairs = &CompilerOptions.User.Args.keyValuePairs;

    //DisplayCommandLineArgs(CompilerOptions.User.args);

    if (vectorContains(*flags, vector<wstring>{L"--show", L"/show", L"-s", L"/s"})) DisplayCommandLineArgs(CompilerOptions.User.Args);

    if (vectorContains(*flags, vector<wstring>{L"--help", L"-h", L"-?", L"/help", L"/h", L"/?"})) {
        DisplayHelp(CompilerOptions.User.Args.programName);
        return 0;
    }

    const bool _feedbackMode = vectorContains(*flags, L"--feedback-mode") ? 1 : 0;

    if (_feedbackMode) _wcout << wstring(20, L'=') << L"[Feedback Mode Enabled]" << wstring(20, L'=') << endl;

    CompilerOptions.verbose = _feedbackMode ? true : vectorContains(*flags, vector<wstring>{L"-v", L"--verbose", L"/verbose"});
    CompilerOptions.Warnings.mayLogWarnings =  _feedbackMode ? true : !vectorContains(*flags, vector<wstring>{L"--no-warnings", L"/no-warnings", L"-nw", L"/nw"});
    CompilerOptions.panic =  _feedbackMode ? false : !vectorContains(*flags, vector<wstring>{L"--no-panic", L"/no-panic", L"-np", L"/np"});
    CompilerOptions.debug = _feedbackMode ? true : vectorContains(*flags, vector<wstring>{L"--debug", L"/debug", L"-d", L"/d"});
    CompilerOptions.allowLexerErrors = _feedbackMode ? true : !vectorContains(*flags, vector<wstring>{L"--no-lexer-errors", L"/no-lexer-errors", L"-nle", L"/nle"});
    CompilerOptions.allowOptimization = _feedbackMode ? true : !vectorContains(*flags, vector<wstring>{L"--no-optimizations", L"/no-optimizations", L"-no-opt", L"/no-opt"});
    if (vectorContains(*flags, vector<wstring>{L"--log-globals"})) {
        _wcout << L"Global Variables:" << endl;
        _wcout << L"_verbose: " << (CompilerOptions.verbose ? L"true" : L"false") << endl;
        _wcout << L"_mayLogWarnings: " << (CompilerOptions.Warnings.mayLogWarnings ? L"true" : L"false") << endl;
        _wcout << L"_panic: " << (CompilerOptions.panic ? L"true" : L"false") << endl;
        _wcout << L"_allowLexerErrors: " << (CompilerOptions.allowLexerErrors ? L"true" : L"false") << endl;
        _wcout << L"_allowOptimization: " << (CompilerOptions.allowOptimization ? L"true" : L"false") << endl;
        _wcout << L"_debug: " << (CompilerOptions.debug ? L"true" : L"false") << endl;
        _wcout << L"_provideHelp: " << (CompilerOptions.provideHelp ? L"true" : L"false") << endl;
        _wcout << L"_feedbackMode: " << (_feedbackMode ? L"true" : L"false") << endl;
    }

    if (CompilerOptions.verbose) _wcout << L"Verbose mode enabled." << endl;

    #pragma region Initialize provided key-value pairs
    wstring inputfilename = L"";
    bool inputfilenameProvided = false;
    wstring outputfilename = L"a";
    bool outputfilenameProvided = false;
    wstring ASToutfilename = L"";
    wstring SToutfilename = L"";
    wstring STDOUTfilename = _feedbackMode ? L"stdout" : L"";
    wstring astDecompilerFilename = L"";
    for (const auto& pair : *keyValuePairs) {
        if (pair.name == L"filename" || pair.name == L"fn") {
            inputfilename = pair.value;
            inputfilenameProvided = true;
            if (CompilerOptions.verbose) _wcout << L"Got inputfilename from key-value pair: " << inputfilename << endl;
        } else if (pair.name == L"output" || pair.name == L"o" || pair.name == L"outfile") {
            outputfilename = pair.value;
            outputfilenameProvided = true;
            if (CompilerOptions.verbose) _wcout << L"Got outputfilename from key-value pair: " << outputfilename << endl;
        } else if (pair.name == L"ast") {
            ASToutfilename = pair.value;
            if (CompilerOptions.verbose) _wcout << L"Got AST output filename from key-value pair: " << ASToutfilename << endl;
        } else if (pair.name == L"st") {
            SToutfilename = pair.value;
            if (CompilerOptions.verbose) _wcout << L"Got ST output filename from key-value pair: " << SToutfilename << endl;
        } else if (pair.name == L"stdout") {
            STDOUTfilename = pair.value;
            if (CompilerOptions.verbose) _wcout << L"Got STDOUT filename from key-value pair: " << STDOUTfilename << endl;
        } else if (pair.name == L"decompile") {
            astDecompilerFilename = pair.value;
            if (CompilerOptions.verbose) _wcout << L"Got AST decompiler output filename from key-value pair: " << astDecompilerFilename << endl;
        }
    }
    #pragma endregion

    wofstream stdoutFile;
    if (!STDOUTfilename.empty()) {  // Reroute _wcout to the specified file
        string narrowSTDOUTfilename(STDOUTfilename.begin(), STDOUTfilename.end());
        stdoutFile.open(narrowSTDOUTfilename.c_str());
        if (stdoutFile.is_open()) {
            stdoutFile.imbue(locale(stdoutFile.getloc(), new codecvt_utf8_utf16<wchar_t>()));
            _wcout.rdbuf(stdoutFile.rdbuf());
            if (CompilerOptions.verbose) _wcout << L"Rerouted STDOUT to " << STDOUTfilename << endl;
        } else {
            _wcout << L"Error: Unable to open STDOUT file for writing." << endl;
            return 1;
        };
    }

    #pragma region Input Filename Extraction
    if (!inputfilenameProvided) {
        if (freeArgs->size() > 0) {
            inputfilename = (*freeArgs)[0];
            inputfilenameProvided = true;
            if (CompilerOptions.verbose) _wcout << L"Got inputfilename from free arguments: " << inputfilename << endl;
        } else {
            _wcout << L"Error: No inputfilename provided." << endl;
            return 1;
        }
    }

    _wcout << L"Input filename: " << inputfilename << endl;
    #pragma endregion
    #pragma region Output Filename Extraction
    if (!outputfilenameProvided) {
        if (freeArgs->size() > 1) {
            outputfilename = (*freeArgs)[1];
            outputfilenameProvided = true;
            if (CompilerOptions.verbose) _wcout << L"Got outputfilename from free arguments: " << outputfilename << endl;
        } else {
            if (CompilerOptions.verbose) _wcout << L"No outputfilename provided, but it's optional so continuing without it." << endl;
        }
    }
    _wcout << L"Output filename: " << outputfilename << endl;
    #pragma endregion
    
    #pragma region File Reading
    string narrowInputFilename(inputfilename.begin(), inputfilename.end());
    ifstream inputFile(narrowInputFilename, ios::binary);
    if (!inputFile.is_open()) {
        _wcout << L"Error: Unable to open input file." << endl;
        return 1;
    }

    stringstream buffer;
    buffer << inputFile.rdbuf();
    string content = buffer.str();
    inputFile.close();

    // Check for and remove UTF-8 BOM (0xEF, 0xBB, 0xBF)
    if (content.size() >= 3 && 
        (unsigned char)content[0] == 0xEF && 
        (unsigned char)content[1] == 0xBB && 
        (unsigned char)content[2] == 0xBF) {
        content.erase(0, 3);
    }

    // Convert UTF-8 bytes to wstring
    wstring fileContent;
    if (!content.empty()) {
        int size_needed = MultiByteToWideChar(CP_UTF8, 0, content.c_str(), (int)content.size(), NULL, 0);
        fileContent.resize(size_needed);
        MultiByteToWideChar(CP_UTF8, 0, content.c_str(), (int)content.size(), &fileContent[0], size_needed);
    }

    if (CompilerOptions.verbose) _wcout << L"Read input file content successfully." << endl;
    #pragma endregion

    vector<lexer::Token> tokens = lexer::Tokenize(fileContent);

    #pragma region Token outfile
    if (!SToutfilename.empty()) {
        string narrowSToutFilename(SToutfilename.begin(), SToutfilename.end());
        filesystem::path p(narrowSToutFilename);
        if (p.has_parent_path() && !filesystem::exists(p.parent_path())) {
            filesystem::create_directories(p.parent_path()); // Létrehozza a teljes mappastruktúrát
        }
        ofstream stOutFile(narrowSToutFilename.c_str());
        if (stOutFile.is_open()) {
            for (size_t i = 0; i < tokens.size() - 1; i++) {
                const auto& token = tokens[i];
                wstringstream ss;
                token.Debug(ss);
                stOutFile << wstringToUTF8(ss.str());
                _wcout << L"[ST] Wrote token " << i + 1 << L"/" << tokens.size() << L" to symbol table output file (" + lexer::TokenKindString(token.kind) + L")     \r";
            }
            _wcout << L"[ST] Wrote token " << tokens.size() << L"/" << tokens.size() << L" to symbol table output file.";
            _wcout << L"\n[ST] Writing last token to symbol table output file..." << endl;
            const auto& lastToken = tokens.back();
            wstringstream ss;
            lastToken.Debug(ss, false);
            stOutFile << wstringToUTF8(ss.str());
            stOutFile.close();
            _wcout << L"[ST] Successfully wrote tokens to " << SToutfilename << endl;
        } else {
            _wcout << L"[ST] Error: Unable to open symbol table output file." << endl;
        }
    }
    #pragma endregion

    if (vectorContains(*flags, vector<wstring>{L"--show-tokens", L"/show-tokens", L"-st", L"/st"})) {
        for (const auto& token : tokens) {
            token.Debug();
        }
    }

    if (_feedbackMode) {
        _wcout << L"\n[Feedback Mode] Tokens generated by the lexer:" << endl;
        for (const auto& token : tokens) {
            wstringstream ss;
            token.Debug(ss);
            _wcout << UTF8ToWstring(wstringToUTF8(ss.str()));
        }
        _wcout << L"[Feedback Mode] End of token display." << endl;
    }

    ast::BlockStmt ast = ast::BlockStmt::Null();
    try {
        ast = parser::Parse(tokens);
    } catch (const exception& e) {
        _wcout << L"[AST] Error during parsing: " << e.what() << endl;
        return 1;
    }

    ast::precompiler::PreCompile(&ast);

    #pragma region AST Decompiler

    if (!astDecompilerFilename.empty()) {
        string narrowASTDecompilerFilename(astDecompilerFilename.begin(), astDecompilerFilename.end());
        ofstream astDecompilerFile(narrowASTDecompilerFilename.c_str());
        if (astDecompilerFile.is_open()) {
            _wcout << L"[AST Decompiler] Writing AST to file..." << endl;
            wstringstream ss;
            wstring decompiled = ast::decompiler::Decompile(ast, inputfilename);
            astDecompilerFile << wstringToUTF8(decompiled);
            astDecompilerFile.close();
            _wcout << L"[AST Decompiler] Successfully wrote decompiled AST to " << astDecompilerFilename << endl;
        } else {
            _wcout << L"[AST Decompiler] Error: Unable to open AST decompiler output file." << endl;
        }
    }

    #pragma endregion
    #pragma region AST outfile
    if (!ASToutfilename.empty()) {
        string narrowASToutFilename(ASToutfilename.begin(), ASToutfilename.end());
        ofstream astOutFile(narrowASToutFilename.c_str());
        if (astOutFile.is_open()) {
            _wcout << L"[AST] Writing AST to file..." << endl;
            wstringstream ss;
            ast.Dump(0, ss);
            astOutFile << wstringToUTF8(ss.str());
            astOutFile.close();
            _wcout << L"[AST] Successfully wrote AST to " << ASToutfilename << endl;
        } else {
            _wcout << L"[AST] Error: Unable to open AST output file." << endl;
        }
    }
    #pragma endregion

    if (vectorContains(*flags, vector<wstring>{L"--show-ast", L"/show-ast", L"-ast", L"/ast"})) {
        _wcout << L"\nAST Structure:" << endl;
        ast.Dump();
    }

    IR::Node* irRoot = IR::MConvert(&ast);
    if (vectorContains(*flags, vector<wstring>{L"--show-ir", L"/show-ir", L"-ir", L"/ir"})) {
        if (irRoot == nullptr) {
            _wcout << L"[IR] No IR generated (irRoot is nullptr)." << endl;
        } else {
            _wcout << L"\nIR Structure: (" << irRoot->getInstructionCount() - 2 << "+2)" << endl;
            IR::Node* current = irRoot;
            while (current) {
                current->instruction.Dump();
                current = current->next;
            }
        }
    }
    irRoot->freeAll();  // Free the entire IR linked list to prevent memory leaks

    if (_feedbackMode) {
        _wcout << L"\n[Feedback Mode] AST generated by the parser:" << endl;
        ast.Dump();
        _wcout << L"[Feedback Mode] End of AST display." << endl;
    }

    if (_feedbackMode) {

    }

    if (_feedbackMode) {
        // Write source code to STDOUT for feedback mode
        _wcout << L"\n[Feedback Mode] Source code:" << endl;
        _wcout << fileContent << endl;

        _wcout << L"[Feedback Mode] End of feedback." << endl;
    }

    if (CompilerOptions.debug) _wcout << L"Program finished successfully." << endl;
    return 0;
}